const dictionaries: Record<Language, Dictionary> = { en, ko, ja, zh };

type I18nValue = string | number;
type I18nContextValue = {
  language: Language;
  setLanguage: (language: Language) => void;
  t: (key: TranslationKey, values?: Record<string, I18nValue>) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem("liminal-wiki:language");
    if (saved === "en" || saved === "ko" || saved === "ja" || saved === "zh")
      window.queueMicrotask(() => setLanguageState(saved));
  }, []);

  useEffect(() => {
    document.documentElement.lang = language === "zh" ? "zh-CN" : language;
  }, [language]);

  const setLanguage = useCallback((nextLanguage: Language) => {
    setLanguageState(nextLanguage);
    window.localStorage.setItem("liminal-wiki:language", nextLanguage);
  }, []);

  const t = useCallback(
    (key: TranslationKey, values?: Record<string, I18nValue>) => {
      let value = dictionaries[language][key] ?? en[key];
      for (const [name, replacement] of Object.entries(values ?? {}))
        value = value.replaceAll(`{{${name}}}`, String(replacement));
      return value;
    },
    [language],
  );

  const context = useMemo(
    () => ({ language, setLanguage, t }),
    [language, setLanguage, t],
  );

  return (
    <I18nContext.Provider value={context}>{children}</I18nContext.Provider>
  );
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}
